CREATE TABLE school_person (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    app_user_id BIGINT NOT NULL UNIQUE REFERENCES app_user(id) ON DELETE CASCADE,
    full_name VARCHAR(160) NOT NULL,
    section_id BIGINT REFERENCES school_section(id)
);

CREATE TABLE attendance_record (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL REFERENCES school_person(id) ON DELETE CASCADE,
    attendance_date DATE NOT NULL,
    status VARCHAR(20) NOT NULL CHECK (status IN ('PRESENT', 'ABSENT', 'LATE')),
    CONSTRAINT uq_attendance_student_date UNIQUE (student_id, attendance_date)
);

CREATE TABLE school_exam (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    section_id BIGINT NOT NULL REFERENCES school_section(id),
    name VARCHAR(100) NOT NULL,
    subject VARCHAR(100) NOT NULL,
    maximum_marks NUMERIC(8, 2) NOT NULL CHECK (maximum_marks > 0),
    CONSTRAINT uq_school_exam_section_name_subject UNIQUE (section_id, name, subject)
);

CREATE TABLE exam_mark (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exam_id BIGINT NOT NULL REFERENCES school_exam(id) ON DELETE CASCADE,
    student_id BIGINT NOT NULL REFERENCES school_person(id) ON DELETE CASCADE,
    obtained_marks NUMERIC(8, 2) NOT NULL CHECK (obtained_marks >= 0),
    CONSTRAINT uq_exam_mark_exam_student UNIQUE (exam_id, student_id)
);
