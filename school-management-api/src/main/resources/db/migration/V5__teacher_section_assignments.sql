CREATE TABLE teacher_section_assignment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    teacher_id BIGINT NOT NULL REFERENCES school_person(id) ON DELETE CASCADE,
    section_id BIGINT NOT NULL REFERENCES school_section(id) ON DELETE CASCADE,
    CONSTRAINT uq_teacher_section_assignment UNIQUE (teacher_id, section_id)
);

CREATE INDEX ix_teacher_section_assignment_section
    ON teacher_section_assignment (section_id);
